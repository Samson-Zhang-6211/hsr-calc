/** 基础攻击力 = 角色基础 + 光锥基础；任一缺失返回 undefined（引擎回退旧口径） */
export function baseAttackOf(
  charId: string | undefined,
  lightconeId: string | undefined,
): number | undefined {
  if (!charId) return undefined;
  const c = CHARACTER_BASE[charId];
  if (!c) return undefined;
  const lc = lightconeId ? LIGHTCONE_BASE[lightconeId] : undefined;
  return lc ? c.atk + lc.atk : c.atk;
}

/** 基础生命 / 防御（角色 + 光锥），规则同上 */
export function baseHpOf(charId: string | undefined, lightconeId?: string): number | undefined {
  const c = charId ? CHARACTER_BASE[charId] : undefined;
  if (!c) return undefined;
  const lc = lightconeId ? LIGHTCONE_BASE[lightconeId] : undefined;
  return lc ? c.hp + lc.hp : c.hp;
}

export function baseDefOf(charId: string | undefined, lightconeId?: string): number | undefined {
  const c = charId ? CHARACTER_BASE[charId] : undefined;
  if (!c) return undefined;
  const lc = lightconeId ? LIGHTCONE_BASE[lightconeId] : undefined;
  return lc ? c.def + lc.def : c.def;
}
