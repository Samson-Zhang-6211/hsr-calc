// 把 render2.ps1 生成的 163 个名字模板（汉仪旗黑 65W）写成 web 端可用的 TS。
// 模板只存「20px 高、二值化、位打包」的名字图像；不含字体文件，字体不进 web 产物。
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const src = join(process.env.TEMP ?? '.', 'hyfont', 'render.json');
const rows = JSON.parse(readFileSync(src, 'utf8').replace(/^\uFEFF/, ''));
const items = rows.map((r) => ({ kind: r.kind, id: String(r.id), name: r.name, w: r.w, h: r.h, data: r.data }));
const header = `// AUTO-GENERATED by scripts/build-name-templates.mjs（2026-10-30）
// 来源：汉仪旗黑 Y3 65W 渲染的 64 个遗器套装名 + 99 个角色名；
// 模板为 20px 高二值位图（位打包），不含字体文件，可安全随 web 发布。
export interface NameTemplate {
  kind: 'relic' | 'char';
  id: string;
  name: string;
  w: number;
  h: number;
  /** 位打包的二值图：bit = y*w+x，MSB 在前 */
  data: string;
}

export const NAME_TEMPLATES: NameTemplate[] = `;
const body = `${JSON.stringify(items, null, 0)};\n`;
writeFileSync('apps/web/src/ocr/name-templates.ts', header + body, 'utf8');
console.log('templates', items.length, 'relic', items.filter((x) => x.kind === 'relic').length, 'char', items.filter((x) => x.kind === 'char').length);
